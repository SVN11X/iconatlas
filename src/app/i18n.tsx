const dict: Record<Lang, Record<Key, string>> = { es, en };

function initialLang(): Lang {
  if (typeof navigator !== 'undefined' && !navigator.language.toLowerCase().startsWith('es')) return 'en';
  return 'es';
}
export const langStore = createStore<Lang>(KEYS.lang, initialLang());

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
  fmt: (n: number) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const lang = useStore(langStore);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = useCallback<TFn>(
    (key, vars) => {
      let s = dict[lang][key] ?? es[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  const value = useMemo<I18nCtx>(() => {
    const nf = new Intl.NumberFormat(lang === 'es' ? 'es-ES' : 'en-US');
    return { lang, setLang: (l) => langStore.set(l), t, fmt: (n) => nf.format(n) };
  }, [lang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const c = useContext(Ctx);
  if (!c) throw new Error('useI18n fuera de I18nProvider');
  return c;
}

